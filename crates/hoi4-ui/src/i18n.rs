#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::{Mutex, MutexGuard, OnceLock};

    fn language_test_guard() -> MutexGuard<'static, ()> {
        static LOCK: OnceLock<Mutex<()>> = OnceLock::new();
        LOCK.get_or_init(|| Mutex::new(())).lock().unwrap()
    }

    #[test]
    fn english_lookup() {
        let _guard = language_test_guard();
        set_language(Language::English);
        assert_eq!(tr("settings_title"), "Settings");
        assert_eq!(tr("fullscreen"), "Fullscreen (borderless)");
    }

    #[test]
    fn chinese_lookup() {
        let _guard = language_test_guard();
        set_language(Language::Chinese);
        assert_eq!(tr("settings_title"), "设置");
        assert_eq!(tr("fullscreen"), "全屏（无边框）");
    }

    #[test]
    fn missing_key_returns_key() {
        let _guard = language_test_guard();
        set_language(Language::English);
        assert_eq!(tr("nonexistent_xyz"), "nonexistent_xyz");
    }

    #[test]
    fn language_from_code() {
        assert_eq!(Language::from_code("zh"), Language::Chinese);
        assert_eq!(Language::from_code("en"), Language::English);
        assert_eq!(Language::from_code("garbage"), Language::English);
    }

    #[test]
    fn hoi4_country_tags_use_vanilla_meanings() {
        let _guard = language_test_guard();
        set_language(Language::Chinese);
        assert_eq!(tr("AUS"), "奥地利");
        assert_eq!(tr("AST"), "澳大利亚");
        assert_eq!(tr("SIK"), "新疆");
        assert_eq!(tr("HBC"), "华北自治会");
        assert_eq!(tr("SND"), "山东军阀");
        assert_eq!(tr("SIC"), "四川军阀");
        assert_eq!(tr("GDC"), "广东军阀");
        assert_eq!(tr("XAJ"), "西安剿总");
        set_language(Language::English);
        assert_eq!(tr("AUS"), "Austria");
        assert_eq!(tr("AST"), "Australia");
        assert_eq!(tr("SIK"), "Sinkiang");
        assert_eq!(tr("HBC"), "North China Autonomous Council");
        assert_eq!(tr("SND"), "Shandong Clique");
        assert_eq!(tr("SIC"), "Sichuan Clique");
        assert_eq!(tr("GDC"), "Guangdong Clique");
        assert_eq!(tr("XAJ"), "Xian Pacification HQ");
    }
}
