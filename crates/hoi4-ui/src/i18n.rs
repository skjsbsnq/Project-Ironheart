//! V5 G.3+：UI 本地化（中英双语）。
//!
//! 极简实现：一个 [`Language`] 枚举 + 一个 [`tr`] 函数按 key 返回当前语言字符串。
//! 所有 UI 文本统一走 `tr("key")`，不再硬编码双语拼接。

/// 支持的语言。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Language {
    English,
    Chinese,
}

impl Language {
    pub fn all() -> &'static [Self] {
        &[Self::Chinese, Self::English]
    }

    pub fn display_name(self) -> &'static str {
        match self {
            Self::English => "English",
            Self::Chinese => "中文",
        }
    }

    pub fn code(self) -> &'static str {
        match self {
            Self::English => "en",
            Self::Chinese => "zh",
        }
    }

    pub fn from_code(s: &str) -> Self {
        match s.trim().to_ascii_lowercase().as_str() {
            "zh" | "chinese" | "cn" => Self::Chinese,
            _ => Self::English,
        }
    }
}

impl Default for Language {
    fn default() -> Self {
        Self::Chinese
    }
}

/// 全局当前语言（简单 static；单线程游戏无竞争）。
static mut CURRENT_LANG: Language = Language::Chinese;

/// 设置当前语言。
pub fn set_language(lang: Language) {
    unsafe {
        CURRENT_LANG = lang;
    }
}

/// 获取当前语言。
pub fn current_language() -> Language {
    unsafe { CURRENT_LANG }
}

/// 按 key 查找当前语言的翻译。找不到时返回 key 本身。
pub fn tr(key: &str) -> &str {
    let lang = current_language();
    lookup(key, lang).unwrap_or(key)
}

fn lookup(key: &str, lang: Language) -> Option<&'static str> {
    let idx = match lang {
        Language::English => 0,
        Language::Chinese => 1,
    };
    TRANSLATIONS
        .iter()
        .find(|(k, _)| *k == key)
        .map(|(_, vals)| vals[idx])
}

